/**
 * Справочный контент страницы «Таймер схватывания».
 *
 * Справка собирается из CURING_PRESETS — тех же карточек, которые
 * показывает инструмент. Подсказки не дублируются руками: если пресет изменят,
 * страница изменится вместе с ним. Отдельно от пресетов живёт только FAQ.
 */

import { CURING_PRESETS } from "./presets";

export interface CuringFaqItem {
  question: string;
  answer: string;
}

export interface CuringCategoryGroup {
  category: string;
  icon: string;
  rows: Array<{ name: string; timing: string; tip: string; source?: { label: string; url: string } }>;
}

/** Пресеты, которые имеет смысл показывать в справочной таблице. */
const TABLE_PRESET_IDS = CURING_PRESETS
  .filter((preset) => preset.id !== "custom")
  .map((preset) => preset.id);

/**
 * Пресеты, сгруппированные по категории работ, в порядке объявления.
 * «Свой таймер» пропускается: у него нет сроков, он не справочная информация.
 */
export function getCuringGroups(): CuringCategoryGroup[] {
  const groups: CuringCategoryGroup[] = [];
  for (const preset of CURING_PRESETS) {
    if (!TABLE_PRESET_IDS.includes(preset.id)) continue;
    let group = groups.find((item) => item.category === preset.category);
    if (!group) {
      group = { category: preset.category, icon: preset.icon, rows: [] };
      groups.push(group);
    }
    group.rows.push({ name: preset.name, timing: preset.description, tip: preset.tip, source: preset.source });
  }
  return groups;
}

