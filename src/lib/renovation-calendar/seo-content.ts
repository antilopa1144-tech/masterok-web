/** Строка таблицы этапов для конкретного сценария. */
export interface ScenarioStageRow {
  title: string;
  summary: string;
  period: string;
}

export interface ScenarioSummary {
  id: RenovationScenario["id"];
  title: string;
  durationLabel: string;
  description: string;
  rows: ScenarioStageRow[];
}

/** Форматирует интервал этапа в дни от старта. */
function formatPeriod(dayFrom: number, dayTo: number): string {
  if (dayFrom === dayTo) return `День ${dayFrom}`;
  return `Дни ${dayFrom}–${dayTo}`;
}

/**
 * Этапы всех сценариев в виде, пригодном для статичной разметки.
 * Источник — RENOVATION_SCENARIOS, поэтому страница и инструмент не разойдутся.
 */
export function getScenarioSummaries(): ScenarioSummary[] {
  return getScenarioList().map((scenario) => ({
    id: scenario.id,
    title: scenario.title,
    durationLabel: scenario.durationLabel,
    description: scenario.description,
    rows: scenario.stages.map((stage) => ({
      title: stage.title,
      summary: stage.summary,
      period: formatPeriod(stage.dayFrom, stage.dayTo),
    })),
  }));
}
