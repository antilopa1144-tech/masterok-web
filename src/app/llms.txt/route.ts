import { ALL_CALCULATORS_META } from "@/lib/calculators/meta.generated";
import { CATEGORIES } from "@/lib/calculators/categories";
import { ALL_TOOLS } from "@/lib/tools";
import { getAllPosts } from "@/lib/blog";
import { SITE_NAME, SITE_URL, SITE_METADATA_DESCRIPTION } from "@/lib/site";

export const dynamic = "force-static";
export const revalidate = 60;

export async function GET() {
  const posts = await getAllPosts();

  const lines: string[] = [];
  lines.push(`# ${SITE_NAME}`);
  lines.push("");
  lines.push(`> ${SITE_METADATA_DESCRIPTION}`);
  lines.push("");
  lines.push(`Сайт ${SITE_NAME} (${SITE_URL}) — бесплатные онлайн-калькуляторы для расчёта строительных материалов. Расчёты с учётом нормативных подходов (ГОСТ, СНиП, СП), практического запаса и упаковки материалов. Все калькуляторы работают без регистрации, полностью на русском языке. Есть мобильное приложение для Android в RuStore.`);
  lines.push("");
  lines.push("## Главные разделы");
  lines.push("");
  lines.push(`- [Главная](${SITE_URL}/): каталог всех калькуляторов`);
  lines.push(`- [Калькуляторы](${SITE_URL}/kalkulyatory/): ${ALL_CALCULATORS_META.length} калькуляторов по категориям`);
  lines.push(`- [Блог](${SITE_URL}/blog/): статьи по строительству и ремонту`);
  lines.push(`- [Михалыч](${SITE_URL}/mikhalych/): AI-помощник строителя`);
  lines.push(`- [Инструменты](${SITE_URL}/instrumenty/): конвертеры, сравнения, чек-листы`);
  lines.push(`- [Мой ремонт](${SITE_URL}/proekty/): проекты, сводные сметы и списки закупки (данные в браузере)`);
  lines.push(`- [Мастер «Мой ремонт»](${SITE_URL}/instrumenty/moy-remont/): ванная/кухня/комната — один ввод размеров, пакет расчётов`);
  lines.push(`- [Календарь ремонта](${SITE_URL}/instrumenty/kalendar-remonta/): этапы, чек-листы и таймеры схватывания по сценарию`);
  lines.push(`- [О проекте](${SITE_URL}/o-proekte/): информация о сервисе`);
  lines.push(`- [Методология расчётов](${SITE_URL}/metodologiya/): источники норм, этапы, запас, упаковки, верификация`);
  lines.push(`- [Приложение](${SITE_URL}/prilozhenie/): мобильное приложение для Android`);
  lines.push(`- [Справка для ИИ](${SITE_URL}/ai/): что считает сайт, как устроены формулы, ограничения`);
  lines.push("");

  lines.push("## Что считает Мастерок");
  lines.push("");
  lines.push("Типовые задачи, под которые на сайте есть отдельный калькулятор:");
  lines.push("");
  lines.push("- расход краски для стен, потолка и фасада с учётом числа слоёв;");
  lines.push("- штукатурка: толщина слоя, тип основания, расход смеси;");
  lines.push("- плитка, клей и затирка для пола и стен;");
  lines.push("- ламинат, линолеум, паркет и подложка — упаковки и запас;");
  lines.push("- стяжка и наливной пол: цемент, песок, вода, толщина;");
  lines.push("- ГКЛ, ГВЛ, ОСБ — листы, профиль, крепёж;");
  lines.push("- фундаменты: бетон, арматура, опалубка, отмостка, подвал;");
  lines.push("- кровля: металлочерепица, профнастил, ондулин, мягкая кровля, водосток;");
  lines.push("- инженерные системы: тёплый пол, радиаторы, электрика, вентиляция, септик, дренаж;");
  lines.push("- фасад и наружная отделка: сайдинг, фасадные панели, утепление, забор, теплица, газон;");
  lines.push("- внутренняя отделка: обои, шпаклёвка, декоративный камень, окна, двери, звукоизоляция.");
  lines.push("");

  lines.push("## Подход к расчётам");
  lines.push("");
  lines.push("- **Нормативные подходы.** За основу берутся отраслевые нормы (ГОСТ, СНиП, СП) и рекомендации производителей материалов. Конкретные источники указываются в блоке нормативной базы на странице каждого калькулятора.");
  lines.push("- **Практический запас.** К чистому объёму добавляется типовой запас на подрезку, бой и отходы — обычно 5–15% в зависимости от материала и способа монтажа.");
  lines.push("- **Упаковка материала.** Результат пересчитывается в реальные единицы продажи: мешки, литры, упаковки, листы, рулоны, погонные метры. Округление вверх до целой упаковки.");
  lines.push("- **Понятный результат.** Помимо итоговой цифры, калькулятор показывает разбивку по компонентам и даёт текстовое пояснение, чтобы пользователь понимал, откуда взялся ответ.");
  lines.push("");

  lines.push("## Ограничения");
  lines.push("");
  lines.push(`${SITE_NAME} — справочный сервис. Калькуляторы дают ориентир по объёму материалов, но не заменяют проектировщика, сметчика и технический надзор. На реальном объекте итоговый расход зависит от состояния основания, квалификации мастера, конкретного производителя смеси, климатических условий и индивидуальных решений по узлам. При работе с несущими и инженерными конструкциями нужен проект.`);
  lines.push("");
  lines.push("## Категории и все калькуляторы");
  lines.push("");
  lines.push(`Всего ${ALL_CALCULATORS_META.length} калькуляторов. Ниже полный перечень по категориям: каждая строка — название, ссылка и то, что именно считает калькулятор.`);
  lines.push("");
  for (const cat of CATEGORIES) {
    const inCategory = ALL_CALCULATORS_META
      .filter((c) => c.category === cat.id)
      .sort((a, b) => b.popularity - a.popularity);
    lines.push(`### ${cat.label}`);
    lines.push("");
    lines.push(`Раздел: ${SITE_URL}/kalkulyatory/${cat.slug}/ — ${inCategory.length} калькуляторов.`);
    lines.push("");
    for (const calc of inCategory) {
      lines.push(`- [${calc.title}](${SITE_URL}/kalkulyatory/${calc.categorySlug}/${calc.slug}/): ${calc.description}`);
    }
    lines.push("");
  }

  lines.push("## Частые вопросы");
  lines.push("");
  lines.push("Ответы ниже даны по устройству расчётов Мастерка, а не по конкретному товару: паспортный расход выбранной марки всегда имеет приоритет.");
  lines.push("");
  lines.push("**Сколько нужно плиточного клея на 1 м²?** Зависит от формата плитки: модель использует укрупнённые полосы расхода — до 20×20 см включительно 3 кг/м², 25×25—45×45 см 5 кг/м², 50×50—80×80 см 7,5 кг/м², от 90×90 см 7,5 кг/м² с множителем ×1,70 на двойное нанесение. Затем применяются коэффициенты места укладки, основания и запас ×1,10.");
  lines.push("");
  lines.push("**Сколько цемента в стяжке?** Модель считает по рецептуре: 325 кг цемента на 1 м³ раствора для пропорции 1:3 и 1200 кг/м³ песка. Толщина учитывается полная, без разбивки на слои, потому что слои и армирование задаёт проект.");
  lines.push("");
  lines.push("**Как считается запас?** К чистому объёму добавляется типовой запас на подрезку, бой и отходы — от 5 до 15% в зависимости от материала и способа монтажа. Точная потребность и количество к покупке показываются раздельно.");
  lines.push("");
  lines.push("**Почему результат отличается от расхода на упаковке клея?** Калькуляторы используют укрупнённые полосы и коэффициенты, а производитель задаёт расход для своего продукта, зуба шпателя и состояния основания. Для закупки сверяйтесь с техкартой выбранной марки.");
  lines.push("");
  lines.push("**Нужен ли проект?** Для несущих конструкций, газа, электрики и сложной гидроизоляции — да. Калькуляторы дают ориентир по объёму материалов, но не заменяют проектировщика.");
  lines.push("");
  lines.push(`Устройство расчётов подробно описано на страницах [методологии](${SITE_URL}/metodologiya/) и [справки о сайте](${SITE_URL}/ai/).`);
  lines.push("");
  lines.push("## Инструменты");
  lines.push("");
  for (const tool of ALL_TOOLS) {
    if (!tool.slug) continue;
    lines.push(`- [${tool.title}](${SITE_URL}/instrumenty/${tool.slug}/): ${tool.description}`);
  }
  lines.push("");
  lines.push("## Последние статьи блога");
  lines.push("");
  for (const post of posts.slice(0, 20)) {
    lines.push(`- [${post.title}](${SITE_URL}/blog/${post.slug}/): ${post.description}`);
  }
  lines.push("");
  lines.push("## Лицензия и использование");
  lines.push("");
  lines.push("Контент сайта можно цитировать с указанием источника. Калькуляторы работают в браузере без отправки данных на сервер. Результаты расчётов носят справочный характер.");
  lines.push("");
  lines.push(`## Контакт`);
  lines.push("");
  lines.push(`Для вопросов по расчётам используйте AI-ассистента Михалыча: ${SITE_URL}/mikhalych/`);
  lines.push("");

  return new Response(lines.join("\n"), {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Cache-Control": "public, max-age=3600",
    },
  });
}
